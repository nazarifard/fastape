package gencode

import (
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"
)

// TODO: check whether this can be removed now that we're using the types generator
func GenCode(pkgName string, t reflect.Type, tapeName string) string {
	tapeTypeStr := tape(t)
	y := t.PkgPath()
	_ = y
	tapeTypeStr = strings.Replace(tapeTypeStr, pkgName+".", "", -1)
	generated_code = strings.Replace(generated_code, pkgName+".", "", -1)

	dontEditMaarker := "// Code generated by fastape - DO NOT EDIT."
	code := dontEditMaarker + "\n"

	code += "package " + pkgName + "\n"
	imports := make([]string, 0, len(generatedTypes)+3)
	seen := make(map[string]struct{}, len(generatedTypes)+3)
	addImport := func(path string) {
		if path == "" {
			return
		}
		if _, ok := seen[path]; ok {
			return
		}
		seen[path] = struct{}{}
		imports = append(imports, path)
	}
	if len(generated_array_map) > 0 {
		addImport("errors")
	}
	if hasTime {
		addImport("time")
	}
	pwd, _ := os.Getwd()
	for kt := range generatedTypes {
		// skip current local package
		if filepath.Base(pwd) == filepath.Base(kt.PkgPath()) {
			continue
		}

		switch kt.PkgPath() {
		case "", t.PkgPath(), pkgName, pwd, filepath.Base(pwd): // skip
		default:
			addImport(kt.PkgPath())
		}
	}
	addImport("github.com/nazarifard/fastape")
	sort.Strings(imports)
	for _, path := range imports {
		code += "import \"" + path + "\"\n"
	}

	// for unnamed type define alias name
	if t.Name() == "" || isFixedSize(t) {
		code += "\n" + "type " + tapeName + " = " + tapeTypeStr
	}

	compile_check_func_code := `
//check compileType error
var _ = func() {
	 var tape %s
	 var v %s
	 _=tape.Sizeof(v)
	 _,_=tape.Roll(v, nil)
	 _,_=tape.Unroll(nil, &v)	
}
`
	code += fmt.Sprintf(compile_check_func_code, tapeName, fmt.Sprint(t))
	code = strings.Replace(code, pkgName+".", "", -1)

	code += "\n" + generated_code
	return code
}
