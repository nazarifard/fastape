package gencode

import (
	"fmt"
	"go/importer"
	"go/types"
	"sort"
	"strings"
)

type typeGenerator struct {
	pkg           *types.Package
	pkgName       string
	imports       map[string]struct{}
	generated     map[types.Type]string
	generatedArr  map[int]bool
	structCounter int
	needsErrors   bool
	timeStruct    *types.Struct
	code          strings.Builder
}

func newTypeGenerator(pkg *types.Package, pkgName string) *typeGenerator {
	return &typeGenerator{
		pkg:          pkg,
		pkgName:      pkgName,
		imports:      make(map[string]struct{}),
		generated:    make(map[types.Type]string),
		generatedArr: make(map[int]bool),
		timeStruct:   loadTimeStruct(),
	}
}

func (g *typeGenerator) Generate(t types.Type, tapeName, typeStrOverride string) (string, error) {
	t = types.Unalias(t)
	tapeTypeStr, err := g.tape(t)
	if err != nil {
		return "", err
	}
	typeStr := typeStrOverride
	if typeStr == "" {
		typeStr = g.typeString(t)
	}

	g.addImport("github.com/nazarifard/fastape")
	if g.needsErrors {
		g.addImport("errors")
	}

	imports := make([]string, 0, len(g.imports))
	for path := range g.imports {
		imports = append(imports, path)
	}
	sort.Strings(imports)

	var out strings.Builder
	out.WriteString("// Code generated by \"fastape\" DO NOT EDIT.\n")
	out.WriteString("package " + g.pkgName + "\n")
	for _, path := range imports {
		out.WriteString("import \"" + path + "\"\n")
	}

	if g.isUnnamed(t) || g.isFixedSize(t) {
		out.WriteString("\n" + "type " + tapeName + " = " + tapeTypeStr)
	}

	compileCheck := `
//check compileType error
var _ = func() {
	 var tape %s
	 var v %s
	 _=tape.Sizeof(v)
	 _,_=tape.Roll(v, nil)
	 _,_=tape.Unroll(nil, &v)	
}
`
	out.WriteString(fmt.Sprintf(compileCheck, tapeName, typeStr))
	out.WriteString("\n" + g.code.String())
	return out.String(), nil
}

func (g *typeGenerator) addImport(path string) {
	if path == "" {
		return
	}
	g.imports[path] = struct{}{}
}

func (g *typeGenerator) qual(p *types.Package) string {
	if p == nil || p.Path() == "" {
		return ""
	}
	if g.pkg != nil && p.Path() == g.pkg.Path() {
		return ""
	}
	g.addImport(p.Path())
	return p.Name()
}

func (g *typeGenerator) typeString(t types.Type) string {
	return types.TypeString(types.Unalias(t), g.qual)
}

func typeStringWithPkgName(t types.Type) string {
	return types.TypeString(types.Unalias(t), func(p *types.Package) string {
		if p == nil {
			return ""
		}
		return p.Name()
	})
}

func (g *typeGenerator) typeName(t types.Type) string {
	if tt, ok := types.Unalias(t).(*types.Named); ok {
		return tt.Obj().Name()
	}
	return ""
}

func (g *typeGenerator) isUnnamed(t types.Type) bool {
	return g.typeName(t) == ""
}

func (g *typeGenerator) isFixedSize(t types.Type) bool {
	switch tt := types.Unalias(t).(type) {
	case *types.Named:
		return g.isFixedSize(tt.Underlying())
	}

	switch tt := types.Unalias(t).(type) {
	case *types.Basic:
		switch tt.Kind() {
		case types.Bool, types.Int, types.Int8, types.Int16, types.Int32, types.Int64,
			types.Uint, types.Uint8, types.Uint16, types.Uint32, types.Uint64,
			types.Float32, types.Float64:
			return true
		default:
			return false
		}
	case *types.Array:
		return g.isFixedSize(tt.Elem())
	case *types.Struct:
		for i := 0; i < tt.NumFields(); i++ {
			if !g.isFixedSize(tt.Field(i).Type()) {
				return false
			}
		}
		return true
	default:
		return false
	}
}

func (g *typeGenerator) isTimeType(t types.Type) bool {
	t = types.Unalias(t)
	st, ok := t.Underlying().(*types.Struct)
	if !ok {
		return false
	}
	if g.timeStruct == nil {
		return false
	}
	if st.NumFields() != g.timeStruct.NumFields() {
		return false
	}
	for i := 0; i < st.NumFields(); i++ {
		field := st.Field(i)
		timeField := g.timeStruct.Field(i)
		if field.Name() != timeField.Name() || typeStringWithPkgName(field.Type()) != typeStringWithPkgName(timeField.Type()) {
			return false
		}
	}
	return true
}

func (g *typeGenerator) underlyingTypeString(t types.Type) string {
	under := types.Unalias(t).Underlying()
	switch tt := under.(type) {
	case *types.Pointer:
		return "*" + g.typeString(tt.Elem())
	case *types.Map:
		return fmt.Sprintf("map[%s]%s", g.typeString(tt.Key()), g.typeString(tt.Elem()))
	case *types.Slice:
		return "[]" + g.typeString(tt.Elem())
	case *types.Array:
		return fmt.Sprintf("[%d]%s", tt.Len(), g.typeString(tt.Elem()))
	case *types.Struct:
		var b strings.Builder
		b.WriteString("struct {")
		for i := 0; i < tt.NumFields(); i++ {
			field := tt.Field(i)
			b.WriteString(fmt.Sprintf("%s %s;", field.Name(), g.typeString(field.Type())))
		}
		b.WriteString("}")
		return b.String()
	case *types.Basic:
		if tt.Kind() == types.String {
			return "string"
		}
		return g.typeString(tt)
	default:
		return g.typeString(tt)
	}
}

func (g *typeGenerator) tape(t types.Type) (result string, err error) {
	t = types.Unalias(t)
	if tape, exists := g.generated[t]; exists {
		return tape, nil
	}

	underType := ""
	defer func() {
		if err != nil {
			return
		}
		if underType != "" {
			result = fmt.Sprintf("fastape.NamedTape[%s, %s, %s]", g.typeString(t), underType, result)
		}
		g.generated[t] = result
	}()

	if g.isFixedSize(t) {
		return fmt.Sprintf("fastape.UnitTape[%s]", g.typeString(t)), nil
	}

	if g.isTimeType(t) {
		underType = "time.Time"
		g.addImport("time")
		return "fastape.TimeTape", nil
	}

	if name := g.typeName(t); name != "" {
		underType = g.underlyingTypeString(t)
	}

	switch tt := t.Underlying().(type) {
	case *types.Basic:
		if tt.Kind() == types.String {
			return "fastape.StringTape", nil
		}
	case *types.Struct:
		structName := g.typeName(t)
		if structName == "" {
			g.structCounter++
			structName = fmt.Sprintf("struct_%04d", g.structCounter)
			g.code.WriteString("\ntype " + structName + " = " + g.structTypeString(tt) + "\n")
		}
		tapeName := structName + "Tape"

		sizeofCode := fmt.Sprintf("\nfunc (t %s) Sizeof(v %s) int {\n size := 0", tapeName, structName)
		rollCode := fmt.Sprintf("\nfunc (t %s) Roll(v %s, bs []byte) (n int, err error) {\tvar m int", tapeName, structName)
		unrollCode := fmt.Sprintf("\nfunc (t %s) Unroll(bs []byte, v *%s) (n int, err error) { var m int", tapeName, structName)

		var tapeFields []string
		for i := 0; i < tt.NumFields(); i++ {
			field := tt.Field(i)
			fieldTape, tapeErr := g.tape(field.Type())
			if tapeErr != nil {
				return "", tapeErr
			}

			tapeFields = append(tapeFields, fmt.Sprintf("a%s %s", field.Name(), fieldTape))

			sizeofCode += fmt.Sprintf("\nsize += t.a%s.Sizeof(v.%s)", field.Name(), field.Name())
			rollCode += fmt.Sprintf("\nm,err=t.a%s.Roll(v.%s,bs[n:]); if err!=nil{return};n+=m", field.Name(), field.Name())
			unrollCode += fmt.Sprintf("\nm, err = t.a%s.Unroll(bs[n:], &v.%s); if err!=nil{return};n+=m", field.Name(), field.Name())
		}
		sizeofCode += "\nreturn size}\n"
		rollCode += "\nreturn}\n"
		unrollCode += "\nreturn}\n"

		g.code.WriteString(sizeofCode)
		g.code.WriteString(rollCode)
		g.code.WriteString(unrollCode)

		newTapeStruct := fmt.Sprintf("struct {\n%s\n}", strings.Join(tapeFields, "\n"))
		g.code.WriteString("\ntype " + tapeName + " " + newTapeStruct + "\n")
		underType = ""
		return tapeName, nil
	case *types.Array:
		n := int(tt.Len())
		if !g.generatedArr[n] {
			g.code.WriteString(genArrayCode(n))
			g.generatedArr[n] = true
			g.needsErrors = true
		}
		elemTape, tapeErr := g.tape(tt.Elem())
		if tapeErr != nil {
			return "", tapeErr
		}
		arrayType := g.typeString(tt)
		if g.typeName(t) != "" {
			arrayType = g.typeString(t)
		}
		return fmt.Sprintf("Array_%d[%s, %s, %s]", n, arrayType, g.typeString(tt.Elem()), elemTape), nil
	case *types.Slice:
		elemTape, tapeErr := g.tape(tt.Elem())
		if tapeErr != nil {
			return "", tapeErr
		}
		return fmt.Sprintf("fastape.SliceTape[%s, %s]", g.typeString(tt.Elem()), elemTape), nil
	case *types.Map:
		keyTape, tapeErr := g.tape(tt.Key())
		if tapeErr != nil {
			return "", tapeErr
		}
		valTape, tapeErr := g.tape(tt.Elem())
		if tapeErr != nil {
			return "", tapeErr
		}
		return fmt.Sprintf("fastape.MapTape[%s, %s, %s, %s]", g.typeString(tt.Key()), g.typeString(tt.Elem()), keyTape, valTape), nil
	case *types.Pointer:
		elemTape, tapeErr := g.tape(tt.Elem())
		if tapeErr != nil {
			return "", tapeErr
		}
		return fmt.Sprintf("fastape.PtrTape[%s, %s]", g.typeString(tt.Elem()), elemTape), nil
	}

	return "", fmt.Errorf("fatal error: fastape doesnt support type: %s", g.typeString(t))
}

func loadTimeStruct() *types.Struct {
	pkg, err := importer.Default().Import("time")
	if err != nil || pkg == nil {
		return nil
	}
	obj := pkg.Scope().Lookup("Time")
	if obj == nil {
		return nil
	}
	if named, ok := obj.Type().(*types.Named); ok {
		if st, ok := named.Underlying().(*types.Struct); ok {
			return st
		}
	}
	if st, ok := obj.Type().Underlying().(*types.Struct); ok {
		return st
	}
	return nil
}

func (g *typeGenerator) structTypeString(st *types.Struct) string {
	if st.NumFields() == 0 {
		return "struct {}"
	}
	fields := make([]string, 0, st.NumFields())
	for i := 0; i < st.NumFields(); i++ {
		field := st.Field(i)
		fieldType := g.typeString(field.Type())
		if field.Anonymous() {
			fields = append(fields, fieldType+g.fieldTagSuffix(st.Tag(i)))
			continue
		}
		fields = append(fields, field.Name()+" "+fieldType+g.fieldTagSuffix(st.Tag(i)))
	}
	return "struct { " + strings.Join(fields, "; ") + " }"
}

func (g *typeGenerator) fieldTagSuffix(tag string) string {
	if tag == "" {
		return ""
	}
	return " `" + tag + "`"
}

func genArrayCode(n int) string {
	const codeArray = `

type Array_%d[A interface{ ~[%d]V }, V any, VT fastape.Tape[V]] struct{ vt VT }

func (array Array_%d[A, V, VT]) Sizeof(a A) int {
	size := 0
	for i := range a {
		size += array.vt.Sizeof(a[i])
	}
	return size
}

func (array Array_%d[A, V, VT]) Roll(a A, bs []byte) (n int, err error) {
	for i := range len(a) {
		m, err := array.vt.Roll(a[i], bs[n:])
		if err != nil {
			return 0, err
		}
		n += m
	}
	return n, nil
}

func (array Array_%d[A, V, VT]) Unroll(bs []byte, p *A) (n int, err error) {
    if p==nil {
	return 0, errors.New("target pointer is nil")
	}
	for i := range len(*p) {
		m, err := array.vt.Unroll(bs[n:], &(*p)[i])
		if err != nil {
			return 0, err
		}
		n += m
	}
	return n, nil
}

`
	return fmt.Sprintf(codeArray, n, n, n, n, n)
}
